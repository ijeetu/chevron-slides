#!/usr/bin/env python3
"""Regenerate the guest-series script reference from the approved DOCX.

Only word/document.xml is read. The DOCX is never modified. Paragraph order,
empty paragraphs, text, tabs, and in-paragraph line breaks are preserved.
"""

import argparse
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET
import zipfile


ROOT = Path(__file__).resolve().parents[1]
SOURCE = "Viral_Fusion_10.21.26_Slides_36-50_Revised (1).docx"
OUTPUT = ROOT / "lib/guest-series-source.ts"
NS = {"w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main"}
W = "{" + NS["w"] + "}"
SLIDES = [
    ("mo-gawdat", "Mo Gawdat"),
    ("samsung", "Samsung"),
    ("charles-adkins", "Charles Adkins"),
    ("palmer-luckey", "Palmer Luckey / Anduril"),
    ("ford", "Ford Motor Company"),
    ("lynsi-snyder", "Lynsi Snyder / In-N-Out Burger"),
    ("chevron", "Chevron"),
    ("x-energy", "X-energy"),
    ("patrick-soon-shiong", "Dr. Patrick Soon-Shiong"),
    ("brandon-cuevas", "Brandon Cuevas"),
    ("chad-bianco", "Sheriff Chad Bianco"),
    ("spencer-pratt", "Spencer Pratt"),
    ("steve-davis", "Steve Davis / The Boring Company"),
    ("hedera-founders", "Mance Harmon + Dr. Leemon Baird"),
    ("michele-chan", "Michele B. Chan / NantStudios"),
]


def paragraph_text(paragraph):
    pieces = []
    for node in paragraph.iter():
        if node.tag == W + "t":
            pieces.append(node.text or "")
        elif node.tag == W + "tab":
            pieces.append("\t")
        elif node.tag in (W + "br", W + "cr"):
            if node.get(W + "type", "textWrapping") == "textWrapping":
                pieces.append("\n")
    return "".join(pieces)


def extract(source):
    with zipfile.ZipFile(source) as archive:
        document = ET.fromstring(archive.read("word/document.xml"))
    paragraphs = document.findall(".//w:body//w:p", NS)
    overview = []
    slides = []
    destination = overview
    current_kind = "body"
    subtitle = False
    screen_lines = False

    for position, paragraph in enumerate(paragraphs, 1):
        text = paragraph_text(paragraph)
        stripped = text.strip()
        slide_heading = re.match(r"^SLIDE (\d+)\s+[—–-]\s+", stripped, re.I)
        cue = re.match(r"^\[(NARRATOR|GEORGE|EDITOR|JEETU)\b", stripped, re.I)
        style = paragraph.find("./w:pPr/w:pStyle", NS)
        style_name = style.get(W + "val", "") if style is not None else ""

        if slide_heading:
            number = int(slide_heading[1])
            if number != 36 + len(slides) or not 36 <= number <= 50:
                raise ValueError(f"Unexpected slide heading at paragraph {position}: {text}")
            slide_id, name = SLIDES[number - 36]
            slide = {
                "sourceSlide": number,
                "id": slide_id,
                "name": name,
                "sourceDocument": SOURCE,
                "paragraphs": [],
            }
            slides.append(slide)
            destination = slide["paragraphs"]
            current_kind = "body"
            screen_lines = False
            kind = "heading"
            subtitle = True
        elif not stripped:
            kind = "body"
        elif cue:
            speaker = cue[1].lower()
            current_kind = speaker if speaker in ("narrator", "george") else "editor"
            screen_lines = False
            kind = current_kind
            subtitle = False
        elif subtitle:
            kind = "heading"
            subtitle = False
        elif stripped.lower().startswith(("on-screen", "on screen")):
            kind = "on-screen"
            screen_lines = stripped.endswith(":")
        elif screen_lines and stripped == stripped.upper():
            kind = "on-screen"
        elif style_name.startswith("Heading") or (
            destination is overview and stripped == stripped.upper() and len(stripped) < 100
        ):
            kind = "heading"
            screen_lines = False
        else:
            kind = current_kind
            screen_lines = False

        destination.append({"kind": kind, "text": text, "sourceParagraph": position})

    if len(slides) != len(SLIDES):
        raise ValueError(f"Expected all 15 guest sections; found {len(slides)}")
    return overview, slides


HEADER = '''/**
 * Lossless paragraph extraction of the approved October 21 revised guest master.
 * Generated by scripts/import-guest-series-source.py; edit the source DOCX instead.
 * Source text, empty paragraphs, and in-paragraph line breaks are preserved.
 * `kind` is a best-effort reading aid based on speaker/editor cues and headings;
 * the original text remains authoritative. Narration is script text only.
 */
export type GuestSeriesSourceParagraphKind =
  | "narrator"
  | "george"
  | "editor"
  | "on-screen"
  | "heading"
  | "body";

export type GuestSeriesSourceParagraph = {
  kind: GuestSeriesSourceParagraphKind;
  text: string;
  /** One-based paragraph position in word/document.xml. */
  sourceParagraph: number;
};

export type GuestSeriesSourceSlide = {
  sourceSlide: number;
  id: string;
  name: string;
  sourceDocument: string;
  paragraphs: GuestSeriesSourceParagraph[];
};

'''


def render(overview, slides):
    encode = lambda value: json.dumps(value, ensure_ascii=False, indent=2)
    return (
        HEADER
        + f"export const guestSeriesSourceDocument = {json.dumps(SOURCE)};\n\n"
        + "export const guestSeriesSourceOverview: GuestSeriesSourceParagraph[] = "
        + encode(overview)
        + ";\n\n"
        + "export const guestSeriesSourceSlides: GuestSeriesSourceSlide[] = "
        + encode(slides)
        + ";\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify output without writing")
    args = parser.parse_args()
    overview, slides = extract(ROOT / SOURCE)
    expected = render(overview, slides)
    count = len(overview) + sum(len(slide["paragraphs"]) for slide in slides)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            print(f"{OUTPUT.relative_to(ROOT)} differs from the approved DOCX", file=sys.stderr)
            return 1
        print(f"Verified {count} paragraphs across {len(slides)} guest slides")
    else:
        OUTPUT.write_text(expected, encoding="utf-8")
        print(f"Imported {count} paragraphs across {len(slides)} guest slides")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
